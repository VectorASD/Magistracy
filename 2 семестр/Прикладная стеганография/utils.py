import numpy as np # pip install numpy

import math
from functools import lru_cache



"""
Функция norminv(p) реализует аппроксимацию обратной CDF нормального
распределения по методу Питера Акклама (Acklam’s approximation).
Это быстрый и точный алгоритм, позволяющий вычислять z-критические значения
без использования scipy или других статистических пакетов.
"""

@lru_cache
def norminv(p):
    """Аппроксимация обратной CDF нормального распределения (Φ⁻¹)."""
    # коэффициенты аппроксимации Акклама (так по мне, это просто непрямоугольная матрица из строк a,b,c,d)
    a = [ -3.969683028665376e+01,
           2.209460984245205e+02,
          -2.759285104469687e+02,
           1.383577518672690e+02,
          -3.066479806614716e+01,
           2.506628277459239e+00 ]

    b = [ -5.447609879822406e+01,
           1.615858368580409e+02,
          -1.556989798598866e+02,
           6.680131188771972e+01,
          -1.328068155288572e+01 ]

    c = [ -7.784894002430293e-03,
          -3.223964580411365e-01,
          -2.400758277161838e+00,
          -2.549732539343734e+00,
           4.374664141464968e+00,
           2.938163982698783e+00 ]

    d = [ 7.784695709041462e-03,
          3.224671290700398e-01,
          2.445134137142996e+00,
          3.754408661907416e+00 ]

    # границы
    plow  = 0.02425
    phigh = 1 - plow

    if p < plow:
        q = math.sqrt(-2 * math.log(p))
        return (((((c[0]*q + c[1])*q + c[2])*q + c[3])*q + c[4])*q + c[5]) / \
               ((((d[0]*q + d[1])*q + d[2])*q + d[3])*q + 1)

    if p > phigh:
        q = math.sqrt(-2 * math.log(1 - p))
        return -(((((c[0]*q + c[1])*q + c[2])*q + c[3])*q + c[4])*q + c[5]) / \
                 ((((d[0]*q + d[1])*q + d[2])*q + d[3])*q + 1)

    q = p - 0.5
    r = q*q
    return (((((a[0]*r + a[1])*r + a[2])*r + a[3])*r + a[4])*r + a[5])*q / \
           (((((b[0]*r + b[1])*r + b[2])*r + b[3])*r + b[4])*r + 1)

"""
Критическое значение z определяется как квантиль стандартного нормального
распределения:
    z = Φ⁻¹(1 - α/2)

где Φ⁻¹ — обратная функция распределения N(0, 1).

Для α = 0.05 получаем:
    z ≈ 1.96

Это означает, что 95% площади под кривой нормального распределения
находится в интервале [-1.96, 1.96].
"""

@lru_cache
def z_from_alpha(alpha):
    return norminv(1 - alpha/2)



"""
1. Доверительный интервал среднего

Пусть имеется выборка X = {x1, x2, ..., xn}.
Тогда выборочное среднее и выборочное стандартное отклонение:
    avg = (1/n) * Σ xi
    std = sqrt( (1/(n-1)) * Σ (xi - avg)^2 )

Доверительный интервал уровня значимости α определяется формулой:
    CI = avg ± z * (std / sqrt(n))

где:
    - n — размер выборки,
    - std — выборочное стандартное отклонение,
    - z — критическое значение нормального распределения.

~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

2. Почему используется нормальное распределение?

При достаточно большом размере выборки (обычно n ≥ 30)
распределение выборочного среднего согласно центральной предельной теореме
стремится к нормальному, независимо от распределения исходных данных.

В нашем случае выборка PSNR по изображениям достаточно велика,
поэтому можно использовать нормальное приближение вместо t-распределения.

Итоговая формула доверительного интервала:
    low  = avg - z * std / sqrt(n)
    high = avg + z * std / sqrt(n)

Этот интервал показывает диапазон, в котором с вероятностью 95% (1−α=0.95)
лежит истинное среднее значение PSNR.

Практический смысл:
    Среднее значение PSNR само по себе не отражает стабильность метода.
    Доверительный интервал показывает, насколько сильно варьируется качество
    между разными изображениями. Узкий интервал означает стабильность,
    широкий — высокую вариативность и меньшую надёжность метода.
"""

@lru_cache
def confidence_interval(avg, std, n, alpha=0.05):
    z = z_from_alpha(alpha)
    margin = z * std / math.sqrt(n)
    return avg - margin, avg + margin



def conv_kernel(pix: np.ndarray, kernel: np.ndarray, mode: str="valid") -> np.ndarray:
    """
    Свёртка ядром kernel.
    Использует только ненулевые коэффициенты.
    pix    — 2D float32
    kernel — 2D float32/int
    mode:
      - "valid": ужимающая свёртка (как раньше)
      - "same":  свёртка с паддингом, выход совпадает с размером pix
    """

    assert pix.ndim == 2
    kh, kw = kernel.shape
    H, W = pix.shape
    if mode not in ("valid", "same"):
        raise ValueError("mode должен быть 'valid' или 'same'")

    if mode == "same":
        if kh % 2 == 0 or kw % 2 == 0:
            raise ValueError(
                "Больше невозможно поддерживать ядра чётного размера (diff и roberts)"
                "из-за особенности адаптивного режима (просто нет центра в свёртке, но padding нужен!)"
            )

        pad_y = kh // 2
        pad_x = kw // 2

        pix = np.pad(
            pix,
            ((pad_y, pad_y), (pad_x, pad_x)),
            mode='edge'
        )

        # после паддинга размер меняется
        H, W = pix.shape

    # общая логика для обоих режимов
    out_h = H - kh + 1
    out_w = W - kw + 1

    out = np.zeros((out_h, out_w), dtype=np.float32)

    for dy in range(kh):
        for dx in range(kw):
            k = kernel[dy, dx]
            if k == 0:
                continue

            region = pix[dy:dy+out_h, dx:dx+out_w]

            # Оптимизация:
            sign, k = k < 0, abs(k)

            if k == 1: term = region
            else:      term = region * k

            if sign: out -= term
            else:    out += term

    return out

